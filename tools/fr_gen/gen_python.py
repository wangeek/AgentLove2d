def _ops_literal(rows):
    """行 dict 列表 → OPS 字面量文本块（opcode=数据行序，0 起）。"""
    lines = []
    for i, r in enumerate(rows):
        fields = ", ".join('("%s", "%s")' % (name, typ) for name, typ in r["fields"])
        variadic = '"%s"' % r["variadic"] if r["variadic"] else "None"
        comma = "," if i < len(rows) - 1 else ""
        lines.append('    {"op": "%s", "section": "%s", "opcode": %d, "fields": [%s], "variadic": %s}%s'
                     % (r["op"], r["section"], i, fields, variadic, comma))
    return "OPS = [\n%s\n]" % "\n".join(lines)


# 模板引擎已处理的类型集与变长标记（表内出现未覆盖者 → 生成期报错）
_HANDLED_TYPES = {"u8", "u32", "f32", "f64", "rgba8", "str", "variant", "f32[]"}
_HANDLED_VARIADIC = {"args...", "payload..."}


def _check_coverage(rows):
    """类型覆盖断言：rows 用到的字段类型/变长标记必须全部被模板引擎处理。"""
    used = {t for r in rows for _, t in r["fields"]}
    used |= {r["variadic"] for r in rows if r["variadic"]}
    unhandled = used - _HANDLED_TYPES - _HANDLED_VARIADIC
    if unhandled:
        raise ValueError("模板引擎未覆盖的类型/变长标记: %s" % sorted(unhandled))


# ---- L0（Lua）侧顺带生成：l0/fr_ops.lua + l0/fr_samples.lua（B3b Task 1）----
# 单一真源纪律：L0 行元数据与样例不手抄，从 cmd.tbl / samples() 生成。
# fr_samples 的 Lua 值约定（与 l0/fr.lua tok_variant 配对，Task 1 定死）：
#   variant num = 裸数；variant bool = 裸布尔；variant str = 单元素表 { '...' }；
#   rgba8 = 4 元表；f32[] 点列 = { {x,y}, ... }；bytes 字段 → data_hex 十六进制串。


def _lua_qstr(s):
    """str → Lua 单引号字面量：转义 \\ 与 '、\\n/\\r/\\t 用具名转义，其余 C0 与
    DEL 用 \\ddd 三位十进制（避免后随数字粘连）；非 ASCII 按原样透传（源码 UTF-8）。"""
    out = []
    for ch in s:
        cp = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif cp < 0x20 or cp == 0x7F:
            out.append("\\%03d" % cp)
        else:
            out.append(ch)
    return "'" + "".join(out) + "'"


def _lua_val(v):
    """自检样本值 → Lua 字面量（见上值约定）。"""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, (bytes, bytearray)):
        return _lua_qstr(bytes(v).hex())
    if isinstance(v, str):
        return _lua_qstr(v)
    if isinstance(v, tuple) and len(v) == 4:            # rgba8
        return "{%s}" % ", ".join(str(int(c)) for c in v)
    if isinstance(v, tuple) and len(v) == 1:            # variant 规范形
        x = v[0]
        if isinstance(x, str):
            return "{%s}" % _lua_qstr(x)
        if isinstance(x, bool):
            return "true" if x else "false"
        raise ValueError("variant 数值载荷样本不经 tuple 包装: %r" % (v,))
    if isinstance(v, list):
        if v and all(isinstance(p, tuple) and len(p) == 2 for p in v):  # f32[] 点列
            return "{%s}" % ", ".join("{%s, %s}" % (repr(p[0]), repr(p[1])) for p in v)
        return "{%s}" % ", ".join(_lua_val(x) for x in v)               # args... 变长
    raise ValueError("样本值类型不支持: %r" % (v,))


def _lua_ops_literal(rows):
    """行 dict 列表 → l0/fr_ops.lua 文本（op → fields/variadic/section + asset kinds）。"""
    lines = [
        "-- GENERATED by fr-gen from tables/cmd.tbl — DO NOT EDIT (改表重新生成)",
        "-- L0 行元数据（表驱动单一真源）：op → fields（名/类型序对）/variadic/section。",
        "-- l0/fr.lua 的 render_line 与 L0 run loop 按此驱动；kinds = asset kind 名↔口径值",
        "-- （spec §6.3，与各生成目标 VARIANT/ASSET 常量同源，跨目标相等由对拍锚定）。",
        "local ops = {",
    ]
    for r in rows:
        fields = ", ".join("{'%s', '%s'}" % (n, t) for n, t in r["fields"])
        variadic = "'%s'" % r["variadic"] if r["variadic"] else "nil"
        lines.append("    ['%s'] = { fields = { %s }, variadic = %s, section = '%s' },"
                     % (r["op"], fields, variadic, r["section"]))
    lines.append("}")
    lines.append("ops.kinds = { image = 0, canvas = 1, quad = 2, font = 3 }")
    lines.append("")
    lines.append("return ops")
    return "\n".join(lines) + "\n"


def _lua_samples_literal():
    """self_test_samples() → l0/fr_samples.lua 文本（每行 { op='…', fields={…} }）。"""
    from tools.fr_gen.samples import samples
    lines = [
        "-- GENERATED by fr-gen from tools/fr_gen/samples.py — DO NOT EDIT (改样例重新生成)",
        "-- 24 条自检样本的 Lua 字面量形：与 Python self_test_samples() 同源（Task 1 跨语言",
        "-- 对拍基准）。值形约定见 gen_python._lua_val；bytes 字段以 data_hex 表达，",
        "-- asset 行 render 由 l0/fr.lua 直接取 hex（空串记 '-'，对齐 Python bytes.hex）。",
        "return {",
    ]
    for op, fields in samples():
        parts = []
        for name, v in fields.items():
            key = name + "_hex" if isinstance(v, (bytes, bytearray)) else name
            parts.append("['%s'] = %s" % (key, _lua_val(v)))
        lines.append("    { op = '%s', fields = { %s } }," % (op, ", ".join(parts)))
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_lua_meta(rows, l0_dir):
    """顺带生成 L0 Lua 元数据到 l0_dir（fr_ops.lua / fr_samples.lua，UTF-8 + LF）。

    由再生入口 __main__ 调用（generate() 保持纯函数——tests 以 tmp 路径直调它，
    不许有仓库内副作用）。内容确定性：无时间戳/随机数，同表重复再生逐字节相等。
    """
    import os
    os.makedirs(l0_dir, exist_ok=True)
    texts = (("fr_ops.lua", _lua_ops_literal(rows)),
             ("fr_samples.lua", _lua_samples_literal()))
    for name, txt in texts:
        with open(os.path.join(l0_dir, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(txt)
    return texts


def generate(rows, out_path):
    """生成编解码模块并写 out_path（UTF-8 + LF），返回生成文本。

    生成期自检：类型覆盖断言 + compile() 语法编译——模板或表坏了当场报，不落盘。
    """
    from tools.fr_gen.tbl import tbl_sha256  # 惰性导入：__main__ 直跑时先修 sys.path
    _check_coverage(rows)
    if len(rows) > 255:
        raise ValueError("表行数 %d 超 255：第 0x100 行起 opcode 与 FR_OP_CMNT=0xFF 值域碰撞" % len(rows))
    code = (_TEMPLATE
            .replace("@@SHA@@", tbl_sha256(rows))
            .replace("@@OPS@@", _ops_literal(rows)))
    compile(code, str(out_path), "exec")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(code)
    return code


