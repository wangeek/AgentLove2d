def _ops_literal(rows):
    """行 dict 列表 → OPS 字面量文本块（opcode=数据行序，0 起）。"""
    lines = []
    for i, r in enumerate(rows):
        fields = ", ".join('("%s", "%s")' % (name, typ) for name, typ in r["fields"])
        variadic = '"%s"' % r["variadic"] if r["variadic"] else "None"
        comma = "," if i < len(rows) - 1 else ""
        lines.append('    {"op": "%s", "section": "%s", "opcode": %d, "fields": [%s], "variadic": %s}%s'
                     % (r["op"], r["section"], i, fields, variadic, comma))
    return "OPS = [\n%s\n]" % "\n".join(lines)


# 模板引擎已处理的类型集与变长标记（表内出现未覆盖者 → 生成期报错）
_HANDLED_TYPES = {"u8", "u32", "f32", "f64", "rgba8", "str", "variant", "f32[]"}
_HANDLED_VARIADIC = {"args...", "payload..."}


def _check_coverage(rows):
    """类型覆盖断言：rows 用到的字段类型/变长标记必须全部被模板引擎处理。"""
    used = {t for r in rows for _, t in r["fields"]}
    used |= {r["variadic"] for r in rows if r["variadic"]}
    unhandled = used - _HANDLED_TYPES - _HANDLED_VARIADIC
    if unhandled:
        raise ValueError("模板引擎未覆盖的类型/变长标记: %s" % sorted(unhandled))


def generate(rows, out_path):
    """生成编解码模块并写 out_path（UTF-8 + LF），返回生成文本。

    生成期自检：类型覆盖断言 + compile() 语法编译——模板或表坏了当场报，不落盘。
    """
    from tools.fr_gen.tbl import tbl_sha256  # 惰性导入：__main__ 直跑时先修 sys.path
    _check_coverage(rows)
    if len(rows) > 255:
        raise ValueError("表行数 %d 超 255：第 0x100 行起 opcode 与 FR_OP_CMNT=0xFF 值域碰撞" % len(rows))
    code = (_TEMPLATE
            .replace("@@SHA@@", tbl_sha256(rows))
            .replace("@@OPS@@", _ops_literal(rows)))
    compile(code, str(out_path), "exec")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(code)
    return code


