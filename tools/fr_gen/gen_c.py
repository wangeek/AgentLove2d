def _const_block():
    """口径常量真值 → #define 文本块。"""
    lines = ["#define FR_VARIANT_TAG_%s %d" % (name, val) for name, val in _VARIANT_TAG_VALUES]
    lines += ["#define FR_ASSET_KIND_%s %d" % (name, val) for name, val in _ASSET_KIND_VALUES]
    return "\n".join(lines)


def _ops_enum(rows):
    """行 dict 列表 → 枚举体文本（值 = 数据行序 0 起，两位十六进制；CMNT=0xFF 收尾）。"""
    lines = ["    FR_OP_%s = 0x%02X," % (r["op"].upper(), i) for i, r in enumerate(rows)]
    lines.append("    FR_OP_CMNT = 0xFF")
    return "\n".join(lines)


def _c_params(row):
    """行 dict → C 形参列表文本（参数序 = 表 signature 字段序）。"""
    params = []
    for name, typ in row["fields"]:
        if typ == "f32[]":
            params.append("const float *%s, uint32_t %s_n" % (name, name))
        elif typ in _C_SIMPLE_PARAMS:
            params.append("%s%s" % (_C_SIMPLE_PARAMS[typ], name))
        else:
            raise ValueError("C emit 未覆盖的字段类型: %r (%s.%s)" % (typ, row["op"], name))
    if row["variadic"] == "args...":
        params.append("const fr_variant *args, uint32_t argc")
    elif row["variadic"] is not None:
        raise ValueError("非 asset 行不支持可变长载荷: %r" % row["variadic"])
    return params


def _emit_body(row):
    """行 dict → 函数体语句文本行（opcode 首字节 + 按字段序的静态 put 序列 +
    args... 收尾；每步失败即短路）。"""
    op = row["op"]
    lines = []
    puts = []
    for name, typ in row["fields"]:
        if typ == "u8":
            puts.append("fr_put_u8(b, %s)" % name)
        elif typ == "u32":
            puts.append("fr_put_u32(b, %s)" % name)
        elif typ == "f32":
            puts.append("fr_put_f32(b, %s)" % name)
        elif typ == "f64":
            puts.append("fr_put_f64(b, %s)" % name)
        elif typ == "rgba8":
            puts.append("fr_put_rgba8(b, %s)" % name)
        elif typ == "str":
            puts.append("fr_put_str(b, %s)" % name)
        elif typ == "variant":
            puts.append("fr_put_variant(b, &%s)" % name)
        elif typ == "f32[]":
            puts.append("fr_put_pts(b, %s, %s_n)" % (name, name))
        else:
            raise ValueError("C emit 未覆盖的字段类型: %r (%s.%s)" % (typ, op, name))
    if row["variadic"] == "args...":
        puts.append("ARGS")
    for p in puts:
        if p == "ARGS":
            lines += [
                "    if (argc > 255u) { /* u8 argc 值域守卫，与 Python struct.pack(\"<B\") 同界 */",
                "        return -1;",
                "    }",
                "    if (fr_put_u8(b, (uint8_t)argc)) {",
                "        return -1;",
                "    }",
                "    for (uint32_t i = 0; i < argc; i++) {",
                "        if (fr_put_variant(b, &args[i])) {",
                "            return -1;",
                "        }",
                "    }",
            ]
        else:
            lines += ["    if (%s) {" % p, "        return -1;", "    }"]
    lines.append("    return 0;")
    return lines


def _emit_fn(op, params, head_lines, body_lines):
    """签名 + 头部 put（opcode 等）+ 字段 put 序列 → 完整 C 函数定义文本。"""
    lines = ["int %s(fr_buf *b%s) {" % (op, params), *head_lines, *body_lines, "}"]
    return "\n".join(lines)


def _asset_emits():
    """asset 四合一 → 四具名函数定义（kind 字节由函数身份写死；payload 布局封版
    于 spec §6.3：image=RGBA8 字节+宽高 / canvas=宽高 / quad=6×f32 / font=字号+字节）。"""
    def head():
        return ["    if (fr_put_u8(b, FR_OP_ASSET)) {", "        return -1;", "    }"]

    def put(stmt):
        return ["    if (%s) {" % stmt, "        return -1;", "    }"]

    def kind_lines(name):
        return ["    if (fr_put_u8(b, FR_ASSET_KIND_%s)) {" % name.upper(),
                "        return -1;", "    }"]

    fns = []
    fns.append(_emit_fn(
        "fr_encode_asset_image", ", uint32_t id, uint32_t w, uint32_t h, const uint8_t *data, uint32_t len",
        head() + kind_lines("image") + [l for s in ("fr_put_u32(b, id)", "fr_put_u32(b, w)", "fr_put_u32(b, h)",
                                                    "fr_put_u32(b, len)") for l in put(s)]
        + ["    return fr_buf_put(b, data, len);"], []))
    fns.append(_emit_fn(
        "fr_encode_asset_canvas", ", uint32_t id, uint32_t w, uint32_t h",
        head() + kind_lines("canvas") + [l for s in ("fr_put_u32(b, id)", "fr_put_u32(b, w)", "fr_put_u32(b, h)")
                                          for l in put(s)] + ["    return 0;"], []))
    fns.append(_emit_fn(
        "fr_encode_asset_quad",
        ", uint32_t id, float x, float y, float w, float h, float sw, float sh",
        head() + kind_lines("quad") + [l for s in ("fr_put_u32(b, id)", "fr_put_f32(b, x)", "fr_put_f32(b, y)",
                                                   "fr_put_f32(b, w)", "fr_put_f32(b, h)", "fr_put_f32(b, sw)",
                                                   "fr_put_f32(b, sh)") for l in put(s)]
        + ["    return 0;"], []))
    fns.append(_emit_fn(
        "fr_encode_asset_font", ", uint32_t id, float size, const uint8_t *data, uint32_t len",
        head() + kind_lines("font") + [l for s in ("fr_put_u32(b, id)", "fr_put_f32(b, size)", "fr_put_u32(b, len)")
                                         for l in put(s)] + ["    return fr_buf_put(b, data, len);"], []))
    return fns


def _fn_decls(rows):
    """行 dict 列表 → per-op 类型化声明文本块（表序；asset 就地拆四）。"""
    decls = []
    for r in rows:
        if r["op"] == "asset":
            decls += [
                "int fr_encode_asset_image(fr_buf *b, uint32_t id, uint32_t w, uint32_t h, const uint8_t *data, uint32_t len);",
                "int fr_encode_asset_canvas(fr_buf *b, uint32_t id, uint32_t w, uint32_t h);",
                "int fr_encode_asset_quad(fr_buf *b, uint32_t id, float x, float y, float w, float h, float sw, float sh);",
                "int fr_encode_asset_font(fr_buf *b, uint32_t id, float size, const uint8_t *data, uint32_t len);",
            ]
        else:
            decls.append("int fr_encode_%s(fr_buf *b, %s);" % (r["op"], ", ".join(_c_params(r))))
    return "\n".join(decls)


def _emits_block(rows):
    """行 dict 列表 → per-op 函数定义文本块（表序；asset 就地拆四）。"""
    fns = []
    for r in rows:
        if r["op"] == "asset":
            fns += _asset_emits()
        else:
            head = ["    if (fr_put_u8(b, FR_OP_%s)) {" % r["op"].upper(),
                    "        return -1;", "    }"]
            fns.append(_emit_fn("fr_encode_%s" % r["op"],
                                "".join(", " + p for p in _c_params(r)),
                                head, _emit_body(r)))
    return "\n\n".join(fns)


