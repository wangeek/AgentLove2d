# 自检用提取模式
_H_SHA_RE = re.compile(r'#define FR_CODEC_TBL_SHA256 "([0-9a-f]{64})"')
_H_DEF_RE = re.compile(r"^#define (FR_[A-Z_]+) (\d+)$", re.M)
_H_DECL_RE = re.compile(r"^int (fr_encode_[a-z0-9_]+)\(.*\);$", re.M)
_DRAW_DECL = ("int fr_encode_draw(fr_buf *b, uint32_t tex, uint32_t quad, float x, float y, "
              "float rot, float sx, float sy, float ox, float oy, fr_rgba8 color);")
_FR_VARIANT_TYPEDEF = "typedef struct { uint8_t tag; double num; const char *str; } fr_variant;"
_IDENT_RE = re.compile(r"^[a-z][a-z0-9_]*$")

# C 形参映射（封版于 B3a 计划的签名映射表）：表类型 → C 形参类型文本（直接前缀
# 在形参名前，故除指针外均带尾随空格）；f32[] 特殊（const float *<名>,
# uint32_t <名>_n）；args... 由 variadic 通路处理
_C_SIMPLE_PARAMS = {
    "u8": "uint8_t ",
    "u32": "uint32_t ",
    "f32": "float ",
    "f64": "double ",
    "rgba8": "fr_rgba8 ",
    "str": "const char *",
    "variant": "fr_variant ",
}


def _const_block():
    """口径常量真值 → #define 文本块。"""
    lines = ["#define FR_VARIANT_TAG_%s %d" % (name, val) for name, val in _VARIANT_TAG_VALUES]
    lines += ["#define FR_ASSET_KIND_%s %d" % (name, val) for name, val in _ASSET_KIND_VALUES]
    return "\n".join(lines)


def _ops_enum(rows):
    """行 dict 列表 → 枚举体文本（值 = 数据行序 0 起，两位十六进制；CMNT=0xFF 收尾）。"""
    lines = ["    FR_OP_%s = 0x%02X," % (r["op"].upper(), i) for i, r in enumerate(rows)]
    lines.append("    FR_OP_CMNT = 0xFF")
    return "\n".join(lines)


def _c_params(row):
    """行 dict → C 形参列表文本（参数序 = 表 signature 字段序）。"""
    params = []
    for name, typ in row["fields"]:
        if typ == "f32[]":
            params.append("const float *%s, uint32_t %s_n" % (name, name))
        elif typ in _C_SIMPLE_PARAMS:
            params.append("%s%s" % (_C_SIMPLE_PARAMS[typ], name))
        else:
            raise ValueError("C emit 未覆盖的字段类型: %r (%s.%s)" % (typ, row["op"], name))
    if row["variadic"] == "args...":
        params.append("const fr_variant *args, uint32_t argc")
    elif row["variadic"] is not None:
        raise ValueError("非 asset 行不支持可变长载荷: %r" % row["variadic"])
    return params


def _emit_body(row):
    """行 dict → 函数体语句文本行（opcode 首字节 + 按字段序的静态 put 序列 +
    args... 收尾；每步失败即短路）。"""
    op = row["op"]
    lines = []
    puts = []
    for name, typ in row["fields"]:
        if typ == "u8":
            puts.append("fr_put_u8(b, %s)" % name)
        elif typ == "u32":
            puts.append("fr_put_u32(b, %s)" % name)
        elif typ == "f32":
            puts.append("fr_put_f32(b, %s)" % name)
        elif typ == "f64":
            puts.append("fr_put_f64(b, %s)" % name)
        elif typ == "rgba8":
            puts.append("fr_put_rgba8(b, %s)" % name)
        elif typ == "str":
            puts.append("fr_put_str(b, %s)" % name)
        elif typ == "variant":
            puts.append("fr_put_variant(b, &%s)" % name)
        elif typ == "f32[]":
            puts.append("fr_put_pts(b, %s, %s_n)" % (name, name))
        else:
            raise ValueError("C emit 未覆盖的字段类型: %r (%s.%s)" % (typ, op, name))
    if row["variadic"] == "args...":
        puts.append("ARGS")
    for p in puts:
        if p == "ARGS":
            lines += [
                "    if (argc > 255u) { /* u8 argc 值域守卫，与 Python struct.pack(\"<B\") 同界 */",
                "        return -1;",
                "    }",
                "    if (fr_put_u8(b, (uint8_t)argc)) {",
                "        return -1;",
                "    }",
                "    for (uint32_t i = 0; i < argc; i++) {",
                "        if (fr_put_variant(b, &args[i])) {",
                "            return -1;",
                "        }",
                "    }",
            ]
        else:
            lines += ["    if (%s) {" % p, "        return -1;", "    }"]
    lines.append("    return 0;")
    return lines


def _emit_fn(op, params, head_lines, body_lines):
    """签名 + 头部 put（opcode 等）+ 字段 put 序列 → 完整 C 函数定义文本。"""
    lines = ["int %s(fr_buf *b%s) {" % (op, params), *head_lines, *body_lines, "}"]
    return "\n".join(lines)


def _asset_emits():
    """asset 四合一 → 四具名函数定义（kind 字节由函数身份写死；payload 布局封版
    于 spec §6.3：image=RGBA8 字节+宽高 / canvas=宽高 / quad=6×f32 / font=字号+字节）。"""
    def head():
        return ["    if (fr_put_u8(b, FR_OP_ASSET)) {", "        return -1;", "    }"]

    def put(stmt):
        return ["    if (%s) {" % stmt, "        return -1;", "    }"]

    def kind_lines(name):
        return ["    if (fr_put_u8(b, FR_ASSET_KIND_%s)) {" % name.upper(),
                "        return -1;", "    }"]

    fns = []
    fns.append(_emit_fn(
        "fr_encode_asset_image", ", uint32_t id, uint32_t w, uint32_t h, const uint8_t *data, uint32_t len",
        head() + kind_lines("image") + [l for s in ("fr_put_u32(b, id)", "fr_put_u32(b, w)", "fr_put_u32(b, h)",
                                                    "fr_put_u32(b, len)") for l in put(s)]
        + ["    return fr_buf_put(b, data, len);"], []))
    fns.append(_emit_fn(
        "fr_encode_asset_canvas", ", uint32_t id, uint32_t w, uint32_t h",
        head() + kind_lines("canvas") + [l for s in ("fr_put_u32(b, id)", "fr_put_u32(b, w)", "fr_put_u32(b, h)")
                                          for l in put(s)] + ["    return 0;"], []))
    fns.append(_emit_fn(
        "fr_encode_asset_quad",
        ", uint32_t id, float x, float y, float w, float h, float sw, float sh",
        head() + kind_lines("quad") + [l for s in ("fr_put_u32(b, id)", "fr_put_f32(b, x)", "fr_put_f32(b, y)",
                                                   "fr_put_f32(b, w)", "fr_put_f32(b, h)", "fr_put_f32(b, sw)",
                                                   "fr_put_f32(b, sh)") for l in put(s)]
        + ["    return 0;"], []))
    fns.append(_emit_fn(
        "fr_encode_asset_font", ", uint32_t id, float size, const uint8_t *data, uint32_t len",
        head() + kind_lines("font") + [l for s in ("fr_put_u32(b, id)", "fr_put_f32(b, size)", "fr_put_u32(b, len)")
                                         for l in put(s)] + ["    return fr_buf_put(b, data, len);"], []))
    return fns


def _fn_decls(rows):
    """行 dict 列表 → per-op 类型化声明文本块（表序；asset 就地拆四）。"""
    decls = []
    for r in rows:
        if r["op"] == "asset":
            decls += [
                "int fr_encode_asset_image(fr_buf *b, uint32_t id, uint32_t w, uint32_t h, const uint8_t *data, uint32_t len);",
                "int fr_encode_asset_canvas(fr_buf *b, uint32_t id, uint32_t w, uint32_t h);",
                "int fr_encode_asset_quad(fr_buf *b, uint32_t id, float x, float y, float w, float h, float sw, float sh);",
                "int fr_encode_asset_font(fr_buf *b, uint32_t id, float size, const uint8_t *data, uint32_t len);",
            ]
        else:
            decls.append("int fr_encode_%s(fr_buf *b, %s);" % (r["op"], ", ".join(_c_params(r))))
    return "\n".join(decls)


def _emits_block(rows):
    """行 dict 列表 → per-op 函数定义文本块（表序；asset 就地拆四）。"""
    fns = []
    for r in rows:
        if r["op"] == "asset":
            fns += _asset_emits()
        else:
            head = ["    if (fr_put_u8(b, FR_OP_%s)) {" % r["op"].upper(),
                    "        return -1;", "    }"]
            fns.append(_emit_fn("fr_encode_%s" % r["op"],
                                "".join(", " + p for p in _c_params(r)),
                                head, _emit_body(r)))
    return "\n\n".join(fns)


# ---- fr_selftest.c 生成：字段字面量化与期望字节嵌入 ----

def _c_f32_lit(v):
    """量化域数值 → C float 字面量（%.6f + f 后缀）。"""
    from tools.fr_gen.quantize import qf

    return "%.6ff" % qf(v)


def _c_f64_lit(v):
    """量化域数值 → C double 字面量（%.6f；variant num/bool 载荷用）。"""
    from tools.fr_gen.quantize import qf

    return "%.6f" % qf(v)


def _c_str_lit(s):
    """str → C 字符串字面量（含引号）。反斜杠/双引号转义；非可打印 ASCII 与
    非 ASCII 字符按 UTF-8 字节做三位八进制转义（八进制至多 3 位、自我终结，
    无 \\xNN 的贪心吞并问题）。"""
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= ord(ch) <= 0x7E:
            out.append(ch)
        else:
            for byte in ch.encode("utf-8"):
                out.append("\\%03o" % byte)
    return '"%s"' % "".join(out)


def _c_variant_lit(v):
    """Python variant 值 → C 复合字面量 (fr_variant){tag, num, str}。

    输入为规范形（解码不动点）：num=裸数、str/bool=单元素 tuple；编码侧容忍
    的裸 str/bool 亦接受（样本数据固定，不依赖该容忍）。
    """
    if isinstance(v, tuple):
        if len(v) != 1:
            raise ValueError("variant 只允许裸值或单元素 tuple: %r" % (v,))
        v = v[0]
    if isinstance(v, bool):
        return "(fr_variant){FR_VARIANT_TAG_BOOL, %s, NULL}" % ("1.000000" if v else "0.000000")
    if isinstance(v, str):
        return "(fr_variant){FR_VARIANT_TAG_STR, 0.000000, %s}" % _c_str_lit(v)
    if isinstance(v, (int, float)):
        return "(fr_variant){FR_VARIANT_TAG_NUM, %s, NULL}" % _c_f64_lit(v)
    raise ValueError("variant 值类型不支持: %r" % (v,))


def _bytes_arr(data):
    """bytes → C uint8_t 数组初始化文本。"""
    if not data:
        raise ValueError("空 data 样本不支持（C 零长数组非法）；样本数据为固定定值")
    return ", ".join("0x%02X" % c for c in data)


def _field_args(name, typ, fields, decls):
    """单字段样本值 → C 实参文本列表（variant/f32[] 先落局部声明）。"""
    v = fields[name]
    if typ in ("u8", "u32"):
        return [str(int(v))]
    if typ == "f32":
        return [_c_f32_lit(v)]
    if typ == "f64":
        return [_c_f64_lit(v)]
    if typ == "rgba8":
        return ["(fr_rgba8){%d, %d, %d, %d}" % tuple(v)]
    if typ == "str":
        return [_c_str_lit(v)]
    if typ == "variant":
        nm = "_v_%s" % name  # 块级作用域，各样本块可重名
        decls.append("const fr_variant %s = %s;" % (nm, _c_variant_lit(v)))
        return [nm]
    if typ == "f32[]":
        flat = []
        for x, y in v:
            flat.append(_c_f32_lit(x))
            flat.append(_c_f32_lit(y))
        nm = "_pts_%s" % name
        decls.append("const float %s[] = {%s};" % (nm, ", ".join(flat)))
        return [nm, str(len(v))]
    raise ValueError("C 自检未覆盖的字段类型: %r (%s)" % (typ, name))


def _asset_call(fc, fields):
    """asset 样本 → (C 函数名, 实参列表, 局部声明列表)；kind 字节由函数身份承载。"""
    kind = fields["kind"]
    decls = []
    oid = str(int(fields["id"]))
    if kind == fc.ASSET_KIND_IMAGE:
        decls.append("const uint8_t data[] = {%s};" % _bytes_arr(fields["data"]))
        return ("fr_encode_asset_image",
                [oid, str(int(fields["w"])), str(int(fields["h"])), "data", "(uint32_t)sizeof data"],
                decls)
    if kind == fc.ASSET_KIND_CANVAS:
        return "fr_encode_asset_canvas", [oid, str(int(fields["w"])), str(int(fields["h"]))], decls
    if kind == fc.ASSET_KIND_QUAD:
        return ("fr_encode_asset_quad",
                [oid] + [_c_f32_lit(fields[k]) for k in ("x", "y", "w", "h", "sw", "sh")], decls)
    if kind == fc.ASSET_KIND_FONT:
        decls.append("const uint8_t data[] = {%s};" % _bytes_arr(fields["data"]))
        return ("fr_encode_asset_font", [oid, _c_f32_lit(fields["size"]), "data", "(uint32_t)sizeof data"],
                decls)
    raise ValueError("asset kind 非法: %r" % (kind,))


def _selftest_row(rows_by_op, fc, op, fields, expect):
    """一条样本 → main() 内的块（块级新作用域：buf/b/局部声明逐块独立）。"""
    decls = []
    call_args = []
    if op == "asset":
        fn, call_args, decls = _asset_call(fc, fields)
    else:
        row = rows_by_op[op]
        fn = "fr_encode_%s" % op
        for name, typ in row["fields"]:
            call_args += _field_args(name, typ, fields, decls)
        if row["variadic"] == "args...":
            decls.append("const fr_variant args[] = {%s};"
                         % ", ".join(_c_variant_lit(v) for v in fields["args"]))
            call_args += ["args", str(len(fields["args"]))]
        elif row["variadic"] is not None:
            raise ValueError("非 asset 行不支持可变长载荷: %r" % row["variadic"])
    hex_arr = ", ".join("0x%02X" % c for c in expect)
    lines = ["{ /* %s */" % op,
             "    uint8_t buf[512];",
             "    fr_buf b = {buf, 0, sizeof buf};"]
    lines += ["    " + d for d in decls]
    lines.append("    const uint8_t want[] = {%s}; /* want %s */" % (hex_arr, expect.hex()))
    lines.append("    if (%s(&b, %s) != 0 || fr_check(\"%s\", buf, b.len, want, sizeof want) != 0) {"
                 % (fn, ", ".join(call_args), op))
    lines += ["        fails++;", "    }", "}"]
    return "\n".join(lines)


def _selftest_c(rows):
    """生成 fr_selftest.c 文本：逐共享样本嵌入字段字面量与期望字节。

    期望字节以 Python 目标（tools/fr_codec_gen.encode_row）为真值，生成期惰性
    导入——故改表后须先再生 Python 目标再再生 C（与 AGENTS.md 工作流同序）。
    """
    from tools import fr_codec_gen as fc        # 生成期惰性导入：__main__ 直跑先修 sys.path
    from tools.fr_gen.samples import samples

    rows_by_op = {r["op"]: r for r in rows}
    blocks = []
    sample_list = samples()
    for op, fields in sample_list:
        if op not in rows_by_op:
            raise ValueError("样本 op 不在表内: %r" % op)
        expect = fc.encode_row(op, fields)
        blocks.append(_selftest_row(rows_by_op, fc, op, fields, expect))
    text = (_ST_TEMPLATE
            .replace("@@ROWS@@", "\n".join(blocks))
            .replace("@@N@@", str(len(sample_list))))
    if len(blocks) != len(sample_list):  # 防御：块数与样本数一致
        raise ValueError("自检块数 %d != 样本数 %d" % (len(blocks), len(sample_list)))
    return text


def _check_identifiers(rows):
    """C 标识符合法性断言：op 名必须是小写起头的合法标识符片段（表坏当场报）。"""
    bad = [r["op"] for r in rows if not _IDENT_RE.match(r["op"])]
    if bad:
        raise ValueError("op 名不是合法 C 标识符片段: %s" % bad)


def _self_check(h, rows):
    """生成后自检：重新 parse 生成的 .h，逐项断言与源一致——模板或表坏了当场报。

    校验项：sha 指纹、口径常量名值、枚举条目数（= 行数 + CMNT）、枚举值按表行序、
    per-op 类型化声明面（asset 拆四）逐条在场且总数相符、fr_variant typedef 与
    fr_encode_draw 类型化签名在场。
    """
    from tools.fr_gen.tbl import tbl_sha256  # 惰性导入：__main__ 直跑时先修 sys.path

    m = _H_SHA_RE.search(h)
    if not m or m.group(1) != tbl_sha256(rows):
        raise ValueError("自检失败：FR_CODEC_TBL_SHA256 与表指纹不符")
    defs = dict(_H_DEF_RE.findall(h))
    want = dict(("FR_VARIANT_TAG_%s" % n, str(v)) for n, v in _VARIANT_TAG_VALUES)
    want.update(dict(("FR_ASSET_KIND_%s" % n, str(v)) for n, v in _ASSET_KIND_VALUES))
    if defs != want:
        raise ValueError("自检失败：口径常量与真值不符: %r != %r" % (defs, want))
    enum = re.findall(r"^    FR_OP_([A-Z0-9_]+) = (0x[0-9A-F]{2}),?$", h, re.M)
    if len(enum) != len(rows) + 1:
        raise ValueError("自检失败：枚举条目数 %d != 行数+1 %d" % (len(enum), len(rows) + 1))
    for i, r in enumerate(rows):
        name, val = enum[i]
        if name != r["op"].upper() or val != "0x%02X" % i:
            raise ValueError("自检失败：枚举第 %d 项 %s=%s 与表行 %s 不符" % (i, name, val, r["op"]))
    if enum[-1] != ("CMNT", "0xFF"):
        raise ValueError("自检失败：枚举收尾不是 FR_OP_CMNT = 0xFF: %r" % (enum[-1],))
    decls = _H_DECL_RE.findall(h)
    want_decls = []
    for r in rows:
        if r["op"] == "asset":
            want_decls += ["fr_encode_asset_%s" % k for k in _ASSET_KINDS]
        else:
            want_decls.append("fr_encode_%s" % r["op"])
    if decls != want_decls:
        raise ValueError("自检失败：per-op 类型化声明面与表不符: %r" % decls)
    if _FR_VARIANT_TYPEDEF not in h:
        raise ValueError("自检失败：fr_variant typedef 缺失")
    if _DRAW_DECL not in h:
        raise ValueError("自检失败：fr_encode_draw 类型化签名缺失")


def generate(rows, out_dir):
    """生成 fr_codec.h/.c/fr_selftest.c 写入 out_dir（UTF-8 + LF），
    返回 (h, c, st) 三段文本。

    生成期自检：C 标识符断言 + 生成后 parse 回读 .h 断言 sha/常量/枚举/类型化
    声明面——模板或表坏了当场报，不落盘。期望字节取自 Python 目标（改表后先
    再生 Python 再再生 C）。
    """
    from tools.fr_gen.tbl import tbl_sha256  # 惰性导入：__main__ 直跑时先修 sys.path

    _check_identifiers(rows)
    if len(rows) > 255:
        raise ValueError("表行数 %d 超 255：第 0x100 行起 opcode 与 FR_OP_CMNT=0xFF 值域碰撞" % len(rows))
    h = (_H_TEMPLATE
         .replace("@@SHA@@", tbl_sha256(rows))
         .replace("@@CONSTS@@", _const_block())
         .replace("@@OPS@@", _ops_enum(rows))
         .replace("@@FN_DECLS@@", _fn_decls(rows)))
    c = _C_TEMPLATE.replace("@@EMITS@@", _emits_block(rows))
    st = _selftest_c(rows)
    _self_check(h, rows)
    import pathlib

    out = pathlib.Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "fr_codec.h", "w", encoding="utf-8", newline="\n") as f:
        f.write(h)
    with open(out / "fr_codec.c", "w", encoding="utf-8", newline="\n") as f:
        f.write(c)
    with open(out / "fr_selftest.c", "w", encoding="utf-8", newline="\n") as f:
        f.write(st)
    return h, c, st


