# tools/fr_gen/gen_c.py
"""fr-gen C 生成器：从 cmd.tbl 行 dict 产出 render/fr_codec.h / render/fr_codec.c。

模板法（风格参照 gen_python）：C99、零依赖、单头单源，引擎未来编进魔改 LÖVE。
B0 只封 API 面——opcode 枚举/口径常量/fr_buf/per-op 声明；字段级 emit 随 B1
展开（届时与 Python 目标共用同一字节布局回归），故 fr_encode_* 形参暂为 (fr_buf *b)。
产出确定性：无时间戳/随机数——同表重复再生逐字节相等（UTF-8 + LF）。
改表后运行再生入口：仓库根 `python -m tools.fr_gen.gen_c`（直跑本文件亦可），
重写 render/fr_codec.h/.c 并打印表指纹。
"""

import re

# 口径常量真值（本生成器内的单一来源；跨目标相等由 tests/test_regen_and_c.py
# 对照 tools/fr_codec_gen.py 同名常量锚定）
_VARIANT_TAG_VALUES = [
    ("NUM", 1),
    ("STR", 2),
    ("BOOL", 3),
]
_ASSET_KIND_VALUES = [
    ("IMAGE", 0),
    ("CANVAS", 1),
    ("QUAD", 2),
    ("FONT", 3),
]

# 生成物模板：横幅与中文注释为固定文本；@@SHA@@/@@CONSTS@@/@@OPS@@/@@FN_DECLS@@ 注入。
_H_TEMPLATE = r'''/* GENERATED by fr-gen from tables/cmd.tbl — DO NOT EDIT (改表重新生成) */
/* FR 命令集 C 编解码生成物（B0 只封 API 面）：opcode 枚举 / 口径常量 / fr_buf /
 * per-op 编码声明。字段级 emit 随 B1 展开并回归字节布局。
 */
#ifndef FR_CODEC_GENERATED_H
#define FR_CODEC_GENERATED_H

#include <stdint.h>
#include <stddef.h>

/* 未来被引擎 C++ TU include 时保持 C 链接符号 */
#ifdef __cplusplus
extern "C" {
#endif

#define FR_CODEC_TBL_SHA256 "@@SHA@@"

/* 口径常量（与 Python 生成物 tools/fr_codec_gen.py 同名同值，跨目标相等测试锚） */
@@CONSTS@@

typedef struct { uint8_t r, g, b, a; } fr_rgba8;

/* opcode 枚举：值 = 表数据行序（0x00 起按表行，生成期守卫行数 ≤255 防 0xFF 碰撞）；
 * CMNT 为 .fr 注释行，不占字节序号，固定 0xFF */
typedef enum {
@@OPS@@
} fr_op_t;

typedef struct { uint8_t *p; size_t len, cap; } fr_buf;

/* 追加 n 字节：成功返回 0；参数非法或容量不足返回 -1（不分配，扩容归调用方） */
int fr_buf_put(fr_buf *b, const void *data, size_t n);

/* per-op 编码入口：B0 占位形参列表 (fr_buf *b)；B1 按表签名展开字段参数 */
@@FN_DECLS@@

#ifdef __cplusplus
}
#endif

#endif /* FR_CODEC_GENERATED_H */
'''

_C_TEMPLATE = r'''/* GENERATED by fr-gen from tables/cmd.tbl — DO NOT EDIT (改表重新生成) */
#include "fr_codec.h"
#include <string.h>

int fr_buf_put(fr_buf *b, const void *data, size_t n)
{
    if (b == NULL || data == NULL) {
        return -1;
    }
    if (b->len > b->cap || n > b->cap - b->len) { /* 同型无符号，先比差防溢出 */
        return -1;
    }
    memcpy(b->p + b->len, data, n);
    b->len += n;
    return 0;
}
'''

# 自检用提取模式
_H_SHA_RE = re.compile(r'#define FR_CODEC_TBL_SHA256 "([0-9a-f]{64})"')
_H_DEF_RE = re.compile(r"^#define (FR_[A-Z_]+) (\d+)$", re.M)
_IDENT_RE = re.compile(r"^[a-z][a-z0-9_]*$")


def _const_block():
    """口径常量真值 → #define 文本块。"""
    lines = ["#define FR_VARIANT_TAG_%s %d" % (name, val) for name, val in _VARIANT_TAG_VALUES]
    lines += ["#define FR_ASSET_KIND_%s %d" % (name, val) for name, val in _ASSET_KIND_VALUES]
    return "\n".join(lines)


def _ops_enum(rows):
    """行 dict 列表 → 枚举体文本（值 = 数据行序 0 起，两位十六进制；CMNT=0xFF 收尾）。"""
    lines = ["    FR_OP_%s = 0x%02X," % (r["op"].upper(), i) for i, r in enumerate(rows)]
    lines.append("    FR_OP_CMNT = 0xFF")
    return "\n".join(lines)


def _fn_decls(rows):
    """行 dict 列表 → per-op 声明文本块（B0 占位形参，B1 展开）。"""
    return "\n".join("int fr_encode_%s(fr_buf *b);" % r["op"] for r in rows)


def _check_identifiers(rows):
    """C 标识符合法性断言：op 名必须是小写起头的合法标识符片段（表坏当场报）。"""
    bad = [r["op"] for r in rows if not _IDENT_RE.match(r["op"])]
    if bad:
        raise ValueError("op 名不是合法 C 标识符片段: %s" % bad)


def _self_check(h, rows):
    """生成后自检：重新 parse 生成的 .h，逐项断言与源一致——模板或表坏了当场报。

    校验项：sha 指纹、口径常量名值、枚举条目数（= 行数 + CMNT）、枚举值按表行序、
    per-op 声明逐条在场且总数相符。
    """
    from tools.fr_gen.tbl import tbl_sha256  # 惰性导入：__main__ 直跑时先修 sys.path

    m = _H_SHA_RE.search(h)
    if not m or m.group(1) != tbl_sha256(rows):
        raise ValueError("自检失败：FR_CODEC_TBL_SHA256 与表指纹不符")
    defs = dict(_H_DEF_RE.findall(h))
    want = dict(("FR_VARIANT_TAG_%s" % n, str(v)) for n, v in _VARIANT_TAG_VALUES)
    want.update(dict(("FR_ASSET_KIND_%s" % n, str(v)) for n, v in _ASSET_KIND_VALUES))
    if defs != want:
        raise ValueError("自检失败：口径常量与真值不符: %r != %r" % (defs, want))
    enum = re.findall(r"^    FR_OP_([A-Z0-9_]+) = (0x[0-9A-F]{2}),?$", h, re.M)
    if len(enum) != len(rows) + 1:
        raise ValueError("自检失败：枚举条目数 %d != 行数+1 %d" % (len(enum), len(rows) + 1))
    for i, r in enumerate(rows):
        name, val = enum[i]
        if name != r["op"].upper() or val != "0x%02X" % i:
            raise ValueError("自检失败：枚举第 %d 项 %s=%s 与表行 %s 不符" % (i, name, val, r["op"]))
    if enum[-1] != ("CMNT", "0xFF"):
        raise ValueError("自检失败：枚举收尾不是 FR_OP_CMNT = 0xFF: %r" % (enum[-1],))
    decls = re.findall(r"^int fr_encode_([a-z0-9_]+)\(fr_buf \*b\);$", h, re.M)
    if decls != [r["op"] for r in rows]:
        raise ValueError("自检失败：per-op 声明面与表不符: %r" % decls)


def generate(rows, out_dir):
    """生成 fr_codec.h/.c 写入 out_dir（UTF-8 + LF），返回 (h 文本, c 文本)。

    生成期自检：C 标识符断言 + 生成后 parse 回读 .h 断言 sha/常量/枚举/声明面
    ——模板或表坏了当场报，不落盘。
    """
    from tools.fr_gen.tbl import tbl_sha256  # 惰性导入：__main__ 直跑时先修 sys.path

    _check_identifiers(rows)
    if len(rows) > 255:
        raise ValueError("表行数 %d 超 255：第 0x100 行起 opcode 与 FR_OP_CMNT=0xFF 值域碰撞" % len(rows))
    h = (_H_TEMPLATE
         .replace("@@SHA@@", tbl_sha256(rows))
         .replace("@@CONSTS@@", _const_block())
         .replace("@@OPS@@", _ops_enum(rows))
         .replace("@@FN_DECLS@@", _fn_decls(rows)))
    _self_check(h, rows)
    import pathlib

    out = pathlib.Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "fr_codec.h", "w", encoding="utf-8", newline="\n") as f:
        f.write(h)
    with open(out / "fr_codec.c", "w", encoding="utf-8", newline="\n") as f:
        f.write(_C_TEMPLATE)
    return h, _C_TEMPLATE


if __name__ == "__main__":
    # 再生入口：改表后运行（仓库根 `python -m tools.fr_gen.gen_c`，或直跑本文件）
    import pathlib
    import sys

    root = pathlib.Path(__file__).resolve().parents[2]
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))  # 直跑时 sys.path[0] 是脚本目录，补上仓库根
    from tools.fr_gen import tbl

    rows = tbl.parse((root / "tables" / "cmd.tbl").read_text(encoding="utf-8"))
    generate(rows, root / "render")
    print("render/fr_codec.h/.c 已再生，TBL_SHA256 =", tbl.tbl_sha256(rows))
