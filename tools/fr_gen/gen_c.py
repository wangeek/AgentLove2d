_C_TEMPLATE = r'''/* GENERATED by fr-gen from tables/cmd.tbl — DO NOT EDIT (改表重新生成) */
/* 字段级 emit 已实现（B3a）：per-op 函数体为生成期按表字段序展开的静态 put 序列
 * （非运行时表驱动，与 Python 目标同哲学）。字节布局与 Python 目标的对账由
 * render/fr_selftest.c（嵌入期望字节）跨目标编译运行兜底。
 * 端序备注：多字节量按宿主小端 memcpy 写出（目标平台 x86/x64，与 Python 目标
 * struct.pack("<…") 一致；大端宿主由 selftest 字节比对当场暴露）。
 * Inf/超大浮点：%.6f 产出 inf 文本 → strtod → INF float——与 Python 目标
 * quantize.qf 的 NaN/Inf 拒收不同，样例无 inf，实现从简，由 selftest 字节比对
 * 兜底；NaN 显式拒收。 */
#include "fr_codec.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

int fr_buf_put(fr_buf *b, const void *data, size_t n)
{
    if (b == NULL || data == NULL) {
        return -1;
    }
    if (b->len > b->cap || n > b->cap - b->len) { /* 同型无符号，先比差防溢出 */
        return -1;
    }
    memcpy(b->p + b->len, data, n);
    b->len += n;
    return 0;
}

/* ---- put 辅助族：全部返回 0/-1，失败即短路 ---- */

/* 量化 f64：%.6f → strtod（十进制正确舍入，与 Python quantize.qf 同语义） */
static int fr_qd(double v, double *out)
{
    if (v != v) { /* NaN */
        return -1;
    }
    char buf[64];
    snprintf(buf, sizeof buf, "%.6f", v);
    *out = strtod(buf, NULL);
    return 0;
}

/* 量化 f32：量化到 double 后再转 float（两步各为正确舍入，最终判据归 selftest） */
static int fr_qf(double v, float *out)
{
    double d;
    if (fr_qd(v, &d)) {
        return -1;
    }
    *out = (float)d;
    return 0;
}

static int fr_put_u8(fr_buf *b, uint8_t v)
{
    return fr_buf_put(b, &v, 1);
}

static int fr_put_u32(fr_buf *b, uint32_t v)
{
    return fr_buf_put(b, &v, 4);
}

static int fr_put_f32(fr_buf *b, float v)
{
    float q;
    if (fr_qf(v, &q)) {
        return -1;
    }
    return fr_buf_put(b, &q, 4);
}

static int fr_put_f64(fr_buf *b, double v)
{
    double q;
    if (fr_qd(v, &q)) {
        return -1;
    }
    return fr_buf_put(b, &q, 8);
}

/* str：NUL 结尾按 strlen 求长；含 NUL 的 str 不支持 */
static int fr_put_str(fr_buf *b, const char *s)
{
    size_t n = strlen(s);
    if (n > 0xFFFFFFFFu) {
        return -1;
    }
    if (fr_put_u32(b, (uint32_t)n)) {
        return -1;
    }
    return fr_buf_put(b, s, n);
}

static int fr_put_rgba8(fr_buf *b, fr_rgba8 v)
{
    return fr_buf_put(b, &v, 4);
}

/* 点列：先 u32 点数，后 2n 个量化 f32（x/y 交替） */
static int fr_put_pts(fr_buf *b, const float *pts, uint32_t n)
{
    uint32_t i;
    if (fr_put_u32(b, n)) {
        return -1;
    }
    for (i = 0; i < 2 * n; i++) {
        if (fr_put_f32(b, pts[i])) {
            return -1;
        }
    }
    return 0;
}

/* variant：tag u8；NUM/BOOL 载荷 = 量化 f64；STR 载荷 = u32 长 + 字节 */
static int fr_put_variant(fr_buf *b, const fr_variant *v)
{
    if (v == NULL) {
        return -1;
    }
    if (fr_put_u8(b, v->tag)) {
        return -1;
    }
    if (v->tag == FR_VARIANT_TAG_NUM || v->tag == FR_VARIANT_TAG_BOOL) {
        return fr_put_f64(b, v->num);
    }
    if (v->tag == FR_VARIANT_TAG_STR) {
        return fr_put_str(b, v->str);
    }
    return -1; /* 非法 tag */
}

@@EMITS@@

@@DECODE@@
'''

