# 自测缓冲口径（生成期守卫 golden 全部行可容；C 侧 decl 与此同源）
_GOLDEN_STR_CAP = 256    # str 出参（含 NUL 位）
_GOLDEN_VS_CAP = 64      # variant STR 载荷 sbuf（含 NUL 位）
_GOLDEN_ARGS_CAP = 16    # args... variant 数组容量
_GOLDEN_PTS_CAP = 64     # pts 出参 float 元素容量（= 32 点）
_GOLDEN_ROW_CAP = 2048   # 单行重编码缓冲


def _golden_facts(rows, full_sha=None):
    """读 tests/golden/sample.frb → (bytes, 帧数, 首帧行数, cmnt 数)。

    生成期守卫：表指纹须与 golden 头内嵌 sha 一致（改表先重产 golden）；
    全部行须在自测缓冲口径内（str/variant/pts/args/单行重编码字节），
    超限当场报而非留到运行期 ERR_CAP。
    """
    import pathlib

    from tools import fr_codec_gen as fc
    from tools import fr_session as fs
    from tools.fr_gen.tbl import tbl_sha256

    root = pathlib.Path(__file__).resolve().parents[2]
    data = (root / "tests" / "golden" / "sample.frb").read_bytes()
    s = fs.parse_binary(data)
    _sha = full_sha or tbl_sha256(rows)  # B15：ext 过滤后须传全表 sha
    if s["sha"] != _sha:
        raise ValueError("golden sample.frb 表指纹 %s… 与当前 cmd.tbl %s… 不符："
                         "改表后须先重产 golden（l0 产流 + fr_as 封装）再再生 C"
                         % (s["sha"][:12], _sha[:12]))
    frames = [p for k, p in s["entries"] if k == "frame"]
    ncmnt = sum(1 for k, _ in s["entries"] if k == "cmnt")
    if not frames:
        raise ValueError("golden 无 frame entry")
    rows_by_op = {r["op"]: r for r in rows}
    for fi, payload in enumerate(frames):
        for op, fields in payload:
            if op not in rows_by_op:
                raise ValueError("golden 帧 %d 含未知 op: %r" % (fi, op))
            if len(fc.encode_row(op, fields)) > _GOLDEN_ROW_CAP:
                raise ValueError("golden 帧 %d op %s 单行超重编码缓冲 %d"
                                 % (fi, op, _GOLDEN_ROW_CAP))
            r = rows_by_op[op]
            if r["variadic"] == "args..." and len(fields["args"]) >= _GOLDEN_ARGS_CAP:
                raise ValueError("golden 帧 %d op %s args 数超容量 %d" % (fi, op, _GOLDEN_ARGS_CAP))
            for name, typ in r["fields"]:
                v = fields.get(name)
                if typ == "str" and len(v.encode("utf-8")) > _GOLDEN_STR_CAP - 1:
                    raise ValueError("golden 帧 %d op %s 字段 %s 超容量 %d"
                                     % (fi, op, name, _GOLDEN_STR_CAP - 1))
                if typ == "f32[]" and len(v) * 2 > _GOLDEN_PTS_CAP:
                    raise ValueError("golden 帧 %d op %s 字段 %s 点数超容量 %d"
                                     % (fi, op, name, _GOLDEN_PTS_CAP // 2))
                if typ == "variant" and isinstance(v, tuple) and v and isinstance(v[0], str) \
                        and len(v[0].encode("utf-8")) > _GOLDEN_VS_CAP - 1:
                    raise ValueError("golden 帧 %d op %s 字段 %s variant 载荷超容量 %d"
                                     % (fi, op, name, _GOLDEN_VS_CAP - 1))
    return data, len(frames), len(frames[0]), ncmnt


def _golden_case(rows_by_op, op):
    """单 op → switch case 文本：按字段序解码 + 重编码（args 变量名 da* 统一）。"""
    ind = " " * 32
    body = " " * 36
    if op == "asset":
        return "\n".join(_golden_asset_case())
    r = rows_by_op[op]
    decls = []
    enc_args = []
    for name, typ in r["fields"]:
        if typ == "u8":
            decls.append("uint8_t %s = fr_dec_u8(&d);" % name)
            enc_args.append(name)
        elif typ == "u32":
            decls.append("uint32_t %s = fr_dec_u32(&d);" % name)
            enc_args.append(name)
        elif typ == "f32":
            decls.append("float %s = fr_dec_f32(&d);" % name)
            enc_args.append(name)
        elif typ == "str":
            decls.append("char ds_%s[%d];" % (name, _GOLDEN_STR_CAP))
            decls.append("fr_dec_str(&d, ds_%s, sizeof ds_%s);" % (name, name))
            enc_args.append("ds_%s" % name)
        elif typ == "variant":
            decls.append("fr_variant dv_%s;" % name)
            decls.append("char ds_%s[%d];" % (name, _GOLDEN_VS_CAP))
            decls.append("fr_dec_variant(&d, &dv_%s, ds_%s, sizeof ds_%s);" % (name, name, name))
            enc_args.append("dv_%s" % name)
        elif typ == "rgba8":
            decls.append("fr_rgba8 dc_%s = {0, 0, 0, 0};" % name)
            decls.append("fr_dec_rgba8(&d, &dc_%s);" % name)
            enc_args.append("dc_%s" % name)
        elif typ == "f32[]":
            decls.append("float dp_%s[%d];" % (name, _GOLDEN_PTS_CAP))
            decls.append("uint32_t dp_%s_n = 0;" % name)
            decls.append("fr_dec_pts(&d, dp_%s, sizeof dp_%s / sizeof dp_%s[0], &dp_%s_n);"
                         % (name, name, name, name))
            enc_args += ["dp_%s" % name, "dp_%s_n" % name]
        else:
            raise ValueError("golden case 未覆盖的字段类型: %r (%s.%s)" % (typ, op, name))
    if r["variadic"] == "args...":
        decls += ["fr_variant da[%d];" % _GOLDEN_ARGS_CAP,
                  "char da_s[%d][%d];" % (_GOLDEN_ARGS_CAP, _GOLDEN_VS_CAP),
                  "uint32_t da_n = 0;",
                  "fr_dec_args(&d, da, sizeof da / sizeof da[0], &da_s[0][0], "
                  "sizeof da_s[0], &da_n);"]
        enc_args += ["da", "da_n"]
    enc = "fr_encode_%s(&b, %s)" % (op, ", ".join(enc_args))
    lines = [ind + "case FR_OP_%s: {" % op.upper()]
    lines += [body + d for d in decls]
    lines += [body + "if (d.err == 0 && %s != 0) {" % enc,
              body + "    fails++;",
              body + "}",
              body + "break;",
              ind + "}"]
    return "\n".join(lines)


def _golden_asset_case():
    """asset case：按 d.asset_kind 分派四具名编码函数（序列不含 kind 字节）。"""
    ind = " " * 32
    body = " " * 36
    data_decl = ["const uint8_t *data = NULL;", "uint32_t dn = 0;",
                 "fr_dec_data(&d, &data, &dn);"]

    def branch(kw, kind, decls, enc):
        return [body + "%s (d.asset_kind == FR_ASSET_KIND_%s) {" % (kw, kind.upper())] \
            + [body + "    " + dcl for dcl in decls] \
            + [body + "    if (d.err == 0 && %s != 0) {" % enc,
               body + "        fails++;",
               body + "    }",
               body + "}"]

    lines = [ind + "case FR_OP_ASSET: {"]
    lines += branch("if", "image",
                    ["uint32_t id = fr_dec_u32(&d);", "uint32_t w = fr_dec_u32(&d);",
                     "uint32_t h = fr_dec_u32(&d);", "uint32_t len = fr_dec_u32(&d);"] + data_decl,
                    "fr_encode_asset_image(&b, id, w, h, data, len)")
    lines += branch("else if", "canvas",
                    ["uint32_t id = fr_dec_u32(&d);", "uint32_t w = fr_dec_u32(&d);",
                     "uint32_t h = fr_dec_u32(&d);"],
                    "fr_encode_asset_canvas(&b, id, w, h)")
    lines += branch("else if", "quad",
                    ["uint32_t id = fr_dec_u32(&d);", "float x = fr_dec_f32(&d);",
                     "float y = fr_dec_f32(&d);", "float w = fr_dec_f32(&d);",
                     "float h = fr_dec_f32(&d);", "float sw = fr_dec_f32(&d);",
                     "float sh = fr_dec_f32(&d);"],
                    "fr_encode_asset_quad(&b, id, x, y, w, h, sw, sh)")
    lines += branch("else if", "font",
                    ["uint32_t id = fr_dec_u32(&d);", "float size = fr_dec_f32(&d);",
                     "uint32_t len = fr_dec_u32(&d);"] + data_decl,
                    "fr_encode_asset_font(&b, id, size, data, len)")
    lines += [body + "break;", ind + "}"]
    return lines


def _golden_section(rows, full_sha=None):
    """golden 闭环段文本：嵌入全字节 + entry 迭代 + 逐行解码-重编码 memcmp。

    返回 (文本, 帧数, 首帧行数, cmnt 数)——计数同时供 _ST_TEMPLATE 尾部
    "C DECODE OK" 行注入（同源单一真值）。
    """
    data, nf, nr, ncm = _golden_facts(rows, full_sha)
    rows_by_op = {r["op"]: r for r in rows}
    cases = "\n".join(_golden_case(rows_by_op, r["op"]) for r in rows)
    hex_txt = data.hex()
    return _GOLDEN_TEMPLATE \
        .replace("@@BYTES@@", _bytes_arr(data)) \
        .replace("@@HEX@@", hex_txt) \
        .replace("@@CASES@@", cases) \
        .replace("@@NF@@", str(nf)) \
        .replace("@@NR@@", str(nr)) \
        .replace("@@NCM@@", str(ncm)) \
        .replace("@@HEX_LEN@@", str(len(data))), nf, nr, ncm


